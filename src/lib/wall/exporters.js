export const MAX_SIDE = 16384
export const outSize = (d, mult = 1) => ({ w: Math.min(MAX_SIDE, Math.max(16, Math.round(d.size.w * mult))), h: Math.min(MAX_SIDE, Math.max(16, Math.round(d.size.h * mult))) })

async function composeStill(d, W, H, phase, onProgress) {
  const c = await renderToCanvas(d, W, H, phase, onProgress)
  if (d.text.on) { await ensureFonts(d.text); const pr = probe(d, W / H, phase); drawText(c.getContext('2d'), W, H, d.text, textColorFor(pr.avg)) }
  return c
}
const toBlob = (c, mime, q) => new Promise((res, rej) => c.toBlob((b) => (b ? res(b) : rej(new Error('The browser could not encode that size. Try a smaller scale.'))), mime, q))
export const MIME = { png: 'image/png', jpg: 'image/jpeg', webp: 'image/webp' }

export async function exportImage(d, { fmt = 'png', W, H, quality = 1, onProgress }) {
  const c = await composeStill(d, W, H, 0, onProgress)
  const b = await toBlob(c, MIME[fmt], quality)
  c.width = c.height = 0; return b
}
export async function exportPack(d, sizes, { fmt = 'png', quality = 1, onProgress }) {
  const files = {}
  for (let i = 0; i < sizes.length; i++) {
    const [name, w, h] = sizes[i]
    const c = await composeStill(d, w, h, 0)
    const b = await toBlob(c, MIME[fmt], quality); files[`${name}-${w}x${h}.${fmt}`] = new Uint8Array(await b.arrayBuffer()); c.width = c.height = 0
    onProgress?.((i + 1) / sizes.length)
  }
  // store, never compress: PNG/JPEG/WebP are already final-quality files
  return new Blob([zipSync(files, { level: 0 })], { type: 'application/zip' })
}

export function videoTypes() {
  if (typeof MediaRecorder === 'undefined') return []
  const cands = [['mp4', 'video/mp4;codecs=avc1.640034'], ['mp4', 'video/mp4;codecs=avc1.42E01E'], ['mp4', 'video/mp4'], ['webm', 'video/webm;codecs=vp9'], ['webm', 'video/webm;codecs=vp8'], ['webm', 'video/webm']]
  const out = []; for (const [ext, mime] of cands) if (!out.find((o) => o.ext === ext) && MediaRecorder.isTypeSupported(mime)) out.push({ ext, mime }); return out
}
/** real-time capture of the seamless loop */
export function recordLoop(d, { W, H, fps = 30, loops = 1, ext, mime, bps }, onProgress, signal) {
  return new Promise(async (resolve, reject) => {
    try {
      const r = new WallRenderer(); r.setDesign(d, true); r.canvas.width = W; r.canvas.height = H
      const out = document.createElement('canvas'); out.width = W; out.height = H; const ctx = out.getContext('2d')
      let overlay = null
      if (d.text.on) { await ensureFonts(d.text); overlay = document.createElement('canvas'); overlay.width = W; overlay.height = H; drawText(overlay.getContext('2d'), W, H, d.text, textColorFor(probe(d, W / H, 0).avg)) }
      const stream = out.captureStream(fps)
      const rec = new MediaRecorder(stream, { mimeType: mime, videoBitsPerSecond: bps || Math.round(W * H * fps * 0.2) })
      const chunks = []; rec.ondataavailable = (e) => e.data.size && chunks.push(e.data)
      const total = d.loop * loops * 1000; let t0 = 0, raf = 0, stopped = false
      const frame = (now) => {
        if (!t0) t0 = now; const el = now - t0
        const ph = ((el % (d.loop * 1000)) / (d.loop * 1000)) * Math.PI * 2
        r.draw(ph, W, H); ctx.drawImage(r.canvas, 0, 0); if (overlay) ctx.drawImage(overlay, 0, 0)
        onProgress?.(Math.min(1, el / total))
        if (signal?.aborted) { stopped = true; rec.stop(); return }
        if (el >= total) { rec.stop(); return }
        raf = requestAnimationFrame(frame)
      }
      rec.onstop = async () => {
        cancelAnimationFrame(raf); r.dispose()
        let blob = new Blob(chunks, { type: mime.split(';')[0] })
        if (stopped) return reject(new Error('Cancelled'))
        if (ext === 'webm') blob = await new Promise((res) => { try { fixWebm(blob, Math.round(total), res) } catch { res(blob) } })
        resolve(blob)
      }
      rec.start(250); raf = requestAnimationFrame(frame)
    } catch (e) { reject(e) }
  })
}

/** self-contained HTML — Lively / Wallpaper Engine / website hero */
export function liveHTML(d) {
  const u = uniformsFor(normalize(d)); const U = { f: u.f, i: u.i, lab: Array.from(u.lab) }
  return `<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Live background — TheToolTable</title>
<style>html,body{margin:0;height:100%;background:#000;overflow:hidden}canvas{display:block;width:100vw;height:100vh}</style></head>
<body><canvas id="c"></canvas>
<script>
/* Generated by TheToolTable · Background Canvas Studio. Seamless ${d.loop}s loop. Design code: ${encodeDesign(d)} */
const VERT=${JSON.stringify(VERT)},FRAG=${JSON.stringify(FRAG)},U=${JSON.stringify(U)},LOOP=${d.loop};
const c=document.getElementById('c'),gl=c.getContext('webgl2');
function sh(t,s){const x=gl.createShader(t);gl.shaderSource(x,s);gl.compileShader(x);return x}
const p=gl.createProgram();gl.attachShader(p,sh(gl.VERTEX_SHADER,VERT));gl.attachShader(p,sh(gl.FRAGMENT_SHADER,FRAG));gl.linkProgram(p);gl.useProgram(p);gl.bindVertexArray(gl.createVertexArray());
const L=n=>gl.getUniformLocation(p,n);
function size(){const r=Math.min(devicePixelRatio||1,2);c.width=innerWidth*r;c.height=innerHeight*r}addEventListener('resize',size);size();
for(const k in U.f)gl.uniform1f(L(k),U.f[k]);for(const k in U.i)gl.uniform1i(L(k),U.i[k]);gl.uniform3fv(L('u_lab'),new Float32Array(U.lab));gl.uniform2f(L('u_origin'),0,0);
const t0=performance.now();
(function f(now){gl.viewport(0,0,c.width,c.height);gl.uniform2f(L('u_res'),c.width,c.height);gl.uniform1f(L('u_phase'),(((now-t0)/1000)%LOOP)/LOOP*Math.PI*2);gl.drawArrays(gl.TRIANGLES,0,3);requestAnimationFrame(f)})(t0);
</script></body></html>`
}
